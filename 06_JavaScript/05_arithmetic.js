// ---------- Basic Arithmetic ----------

let number1 = 2;
let number2 = 10;

console.log(`The sum of the numbers is: ${number1 + number2}`);

console.log(`The subtraction of the numbers is: ${number1 - number2}`);

console.log(`The division of the numbers is: ${number1 / number2}`);

console.log(`The multiplication of the numbers is: ${number1 * number2}`);


// ---------- Reassigning Numbers ----------

number1 = 5;
number2 = 20;


// ---------- Remainder ----------

console.log(`The reminder of number is :${number1 % number2}`);


// ---------- Power ----------

console.log(`The power of number is :${number1 ** 2}`);

console.log(`The power of number is :${number2 ** 2}`);